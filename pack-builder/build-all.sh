#!/usr/bin/env bash
# PMB OS runtime pack builder - builds every plug&play runtime pack and the repo index.
#
# Host requirements: Linux x86_64 or arm64, bash, docker (or podman via DOCKER=podman).
# On x86_64 hosts arm64 containers run through qemu-user binfmt_misc, e.g.:
#     docker run --privileged --rm tonistiigi/binfmt --install arm64
# (or `apt install qemu-user-static binfmt-support`). On arm64 hosts the wine stage needs
# the amd64 equivalent (`--install amd64`).
#
# Usage: ./build-all.sh [options]
#   -w, --work DIR        work directory (default: ./out next to this script)
#   -u, --base-url URL    public base URL of the archives (written into index.json), e.g.
#                         https://github.com/<owner>/<repo>/releases/download/runtime-1.0.0
#   -s, --stages LIST     comma separated subset of:
#                         images,fetch,pmbshm,libxcb,glibc,rootfs,box64,wine,mesa,repack,post,verify,index
#   -p, --packs "IDS"     only (re)finalize these staged pack ids in the post stage
#   -j, --jobs N          parallel build jobs (default: nproc)
#       --no-verify       skip the verify stage
#   -h, --help
# Every pinned input lives in versions.env; any of its variables can be overridden from
# the environment, e.g.  WINE_VERSIONS=11.0 BOX64_VARIANTS=generic ./build-all.sh
set -euo pipefail

PB_HOST="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PB_LOG_PREFIX=build-all
# shellcheck source=lib/common.sh
. "$PB_HOST/lib/common.sh"
# shellcheck source=versions.env
. "$PB_HOST/versions.env"

ALL_STAGES="images,fetch,pmbshm,libxcb,glibc,rootfs,box64,wine,mesa,repack,post,verify,index"
WORK_HOST="$PB_HOST/out"
BASE_URL="${BASE_URL:-}"
STAGES="$ALL_STAGES"
ONLY_PACKS=""
JOBS="${JOBS:-$(nproc)}"
VERIFY=1
DOCKER="${DOCKER:-docker}"

usage() { awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "${BASH_SOURCE[0]}"; }

while [ $# -gt 0 ]; do
    case "$1" in
        -w|--work) WORK_HOST="$2"; shift 2 ;;
        -u|--base-url) BASE_URL="$2"; shift 2 ;;
        -s|--stages) STAGES="$2"; shift 2 ;;
        -p|--packs) ONLY_PACKS="$2"; shift 2 ;;
        -j|--jobs) JOBS="$2"; shift 2 ;;
        --no-verify) VERIFY=0; shift ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; die "unknown option: $1" ;;
    esac
done

need_cmd "$DOCKER" sha256sum
[ "$(uname -s)" = Linux ] || die "the pack builder runs on Linux hosts"
case "$(uname -m)" in
    x86_64|amd64) HOST_PLATFORM=linux/amd64 ;;
    aarch64|arm64) HOST_PLATFORM=linux/arm64 ;;
    *) die "unsupported host architecture $(uname -m)" ;;
esac
[[ "$JOBS" =~ ^[0-9]+$ ]] && [ "$JOBS" -gt 0 ] || die "invalid --jobs: $JOBS"
IFS=',' read -r -a stage_list <<< "$STAGES"
for s in "${stage_list[@]}"; do
    case ",$ALL_STAGES," in *",$s,"*) ;; *) die "unknown stage: $s" ;; esac
done
want() { case ",$STAGES," in *",$1,"*) return 0 ;; *) return 1 ;; esac; }

# --- glibc pin = the APK's loader (pmbos/tools/loader/VERSION) ----------------------------------
# The stock ld.so shipped as libpmbld.so runs the libc.so.6 rebuilt here: same Debian version, or
# the GLIBC_PRIVATE ABI between them may not match. Refuse any drift before building anything.
check_loader_pin() {
    local f="$PB_HOST/../loader/VERSION" k v
    [ -f "$f" ] || die "$f missing (written by pmbos/tools/loader/fetch-loader.sh)"
    declare -A lv=()
    while IFS='=' read -r k v; do
        case "$k" in ''|\#*) continue ;; esac
        lv[$k]="${v%$'\r'}"
    done < "$f"
    [ "${lv[debian_version]:-}" = "$GLIBC_DEBIAN_VERSION" ] \
        || die "GLIBC_DEBIAN_VERSION=$GLIBC_DEBIAN_VERSION but the APK loader is ${lv[debian_version]:-?} ($f)"
    [ "${lv[deb_sha256]:-}" = "$LIBC6_DEB_SHA256" ] \
        || die "LIBC6_DEB_SHA256 differs from deb_sha256 in $f"
    [ "${lv[loader_sha256]:-}" = "$LOADER_SHA256" ] \
        || die "LOADER_SHA256 differs from loader_sha256 in $f"
    log "glibc pinned to $GLIBC_DEBIAN_VERSION = APK loader (loader/VERSION)"
}
check_loader_pin

mkdir -p "$WORK_HOST"
WORK_HOST="$(cd "$WORK_HOST" && pwd)"

# --- resolved configuration for the containers (bash %q-quoted exports) ---------------------
write_config() {
    local f="$WORK_HOST/config.env" n
    {
        echo "# generated by build-all.sh on $(date -u +%FT%TZ) - do not edit, edit versions.env"
        for n in $(grep -oE '^(: "\$\{)?[A-Z][A-Z0-9_]*' "$PB_HOST/versions.env" | sed 's/^: "\${//' | sort -u); do
            [ -n "${!n+x}" ] && printf 'export %s=%q\n' "$n" "${!n}"
        done
        printf 'export %s=%q\n' BASE_URL "$BASE_URL" JOBS "$JOBS" ONLY_PACKS "$ONLY_PACKS"
    } > "$f.tmp"
    mv -f "$f.tmp" "$f"
}
write_config

# --- docker images ---------------------------------------------------------------------------
declare -A IMAGE PLATFORM
PLATFORM[tools]="$HOST_PLATFORM"
PLATFORM[arm64]=linux/arm64
PLATFORM[amd64]=linux/amd64

image_tag() { # kind
    local h
    h="$( { cat "$PB_HOST/docker/Dockerfile.$1"; echo "$DEBIAN_IMAGE"; echo "$MESA_PIP_PACKAGES"; echo "${PLATFORM[$1]}"; } \
        | sha256sum | cut -c1-12)"
    printf 'pmbos-pack-builder-%s:%s' "$1" "$h"
}

check_emulation() { # platform
    [ "$1" = "$HOST_PLATFORM" ] && return 0
    local m
    m="$("$DOCKER" run --rm --platform "$1" "$DEBIAN_IMAGE" uname -m 2>/dev/null || true)"
    case "$1:$m" in
        linux/arm64:aarch64|linux/amd64:x86_64) return 0 ;;
    esac
    die "cannot run $1 containers on this $HOST_PLATFORM host (got '$m'). Register qemu binfmt handlers:
    $DOCKER run --privileged --rm tonistiigi/binfmt --install ${1#linux/}"
}

ensure_image() { # kind
    local kind="$1" tag
    tag="$(image_tag "$kind")"
    IMAGE[$kind]="$tag"
    if "$DOCKER" image inspect "$tag" >/dev/null 2>&1; then
        return 0
    fi
    check_emulation "${PLATFORM[$kind]}"
    log "building image $tag (${PLATFORM[$kind]})"
    "$DOCKER" build --platform "${PLATFORM[$kind]}" \
        --build-arg "DEBIAN_IMAGE=$DEBIAN_IMAGE" --build-arg "MESA_PIP_PACKAGES=$MESA_PIP_PACKAGES" \
        -f "$PB_HOST/docker/Dockerfile.$kind" -t "$tag" "$PB_HOST/docker"
}

run_stage() { # kind stage-name [extra docker args...]
    local kind="$1" name="$2"
    shift 2
    ensure_image "$kind"
    log "=== stage $name ($kind, ${PLATFORM[$kind]}) ==="
    local t0=$SECONDS
    "$DOCKER" run --rm --platform "${PLATFORM[$kind]}" \
        -v "$PB_HOST:/pb:ro" -v "$WORK_HOST:/work" \
        -e HOST_UID="$(id -u)" -e HOST_GID="$(id -g)" \
        -e PMB_VERIFY_WINE="${PMB_VERIFY_WINE:-auto}" \
        "$@" "${IMAGE[$kind]}" bash "/pb/stages/stage-$name.sh"
    log "=== stage $name done in $((SECONDS - t0))s ==="
}

if want images; then
    for k in tools arm64 amd64; do ensure_image "$k"; done
fi
want fetch  && run_stage tools fetch
want pmbshm && run_stage arm64 pmbshm
want libxcb && run_stage arm64 libxcb
want glibc  && run_stage arm64 glibc
# shellcheck disable=SC2086
want rootfs && run_stage tools rootfs ${PMB_DOCKER_ROOTFS_ARGS:-}
want box64  && run_stage arm64 box64
want wine   && run_stage amd64 wine
want mesa   && run_stage arm64 mesa
want repack && run_stage tools repack
want post   && run_stage tools post
if want verify && [ "$VERIFY" = 1 ]; then run_stage arm64 verify; fi
want index  && run_stage tools index

log "done. Output: $WORK_HOST/dist"
