#!/usr/bin/env bash
# Exports the pack builder into a checkout of the public packs repo (kireikosasha/pmbos-runtime), laid out as
#
#   <target>/.github/workflows/build-packs.yml   GitHub Actions workflow (builds + publishes the packs)
#   <target>/pack-builder/                       this directory (stages, patches, docker, lib, src, files, tests,
#                                                github/ci.sh ...), without out/ and caches
#   <target>/loader/VERSION                      glibc pin of the APK's loader (build-all.sh checks it)
#   <target>/README.md                           repo README (only if missing or generated by this script)
#   <target>/.gitattributes, .gitignore          LF line endings, build outputs ignored
#
# Idempotent: pack-builder/ and the workflow are replaced on every run (files deleted here disappear there);
# .git and anything else in the target are left alone. Nothing is committed or pushed.
#
# Usage: bash pmbos/tools/pack-builder/github/export.sh <target dir>
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PB="$(cd "$HERE/.." && pwd)"
LOADER_VERSION="$PB/../loader/VERSION"
MARK="<!-- generated by pack-builder/github/export.sh -->"

die() { printf 'export.sh: ERROR: %s\n' "$*" >&2; exit 1; }
[ $# -eq 1 ] || { sed -n '2,15s/^# \{0,1\}//p' "${BASH_SOURCE[0]}"; exit 2; }
[ -f "$LOADER_VERSION" ] || die "$LOADER_VERSION missing"
[ -f "$HERE/workflows/build-packs.yml" ] || die "$HERE/workflows/build-packs.yml missing"

parent="$(dirname "$1")"
[ -d "$parent" ] || die "parent directory $parent does not exist"
T="$(cd "$parent" && pwd)/$(basename "$1")"
case "$T/" in
    "$PB/"*) die "target $T is inside the pack builder" ;;
esac
mkdir -p "$T"
T="$(cd "$T" && pwd)"
# never export into the source repository itself (the private app repo or the packs repo we run from)
src_top="$(git -C "$PB" rev-parse --show-toplevel 2>/dev/null || true)"
dst_top="$(git -C "$T" rev-parse --show-toplevel 2>/dev/null || true)"
if [ -n "$src_top" ] && [ -n "$dst_top" ] && [ "$(cd "$src_top" && pwd)" = "$(cd "$dst_top" && pwd)" ]; then
    die "target $T belongs to the same git repository as the pack builder ($src_top)"
fi
[ -n "$dst_top" ] || echo "note: $T is not a git checkout yet (git clone the packs repo there first, or git init)" >&2

echo "exporting $PB -> $T"
rm -rf "$T/pack-builder"
mkdir -p "$T/pack-builder" "$T/.github/workflows" "$T/loader"
# tar keeps modes (executable scripts); excludes build output, caches and the workflow source copy
tar -C "$PB" --exclude=./out --exclude='__pycache__' --exclude='*.pyc' --exclude=./github/workflows -cf - . \
    | tar -C "$T/pack-builder" -xf -
cp "$HERE/workflows/build-packs.yml" "$T/.github/workflows/build-packs.yml"
cp "$LOADER_VERSION" "$T/loader/VERSION"
chmod +x "$T/pack-builder/build-all.sh" "$T/pack-builder/github/"*.sh "$T/pack-builder/tests/"*.sh 2>/dev/null || true

if [ ! -f "$T/README.md" ] || grep -qF "$MARK" "$T/README.md"; then
    { echo "$MARK"; cat "$HERE/REPO_README.md"; } > "$T/README.md"
else
    echo "note: $T/README.md was edited by hand - left unchanged (template: pack-builder/github/REPO_README.md)" >&2
fi

cat > "$T/.gitattributes" <<'EOF'
# generated by pack-builder/github/export.sh: scripts must keep LF on every OS (the runners are Linux)
* text=auto eol=lf
# patches are applied with --fuzz=0: byte-exact, never converted
*.patch -text
*.tar binary
*.xz binary
*.zst binary
*.gz binary
EOF
cat > "$T/.gitignore" <<'EOF'
# generated by pack-builder/github/export.sh: local/CI build outputs
/work/
/artifacts/
/images/
/release-extra/
/pack-builder/out/
__pycache__/
EOF

# sanity: the layout build-all.sh expects (loader pin at ../loader/VERSION) and CRLF-free scripts
[ -f "$T/pack-builder/build-all.sh" ] && [ -f "$T/pack-builder/github/ci.sh" ] || die "export incomplete"
# (counted with tr: MSYS grep on Windows treats a pattern of "\r" as empty and would match every file)
crlf=""
while IFS= read -r -d '' f; do
    [ "$(tr -dc '\r' < "$f" | wc -c)" -eq 0 ] || crlf="$crlf ${f#"$T"/}"
done < <(find "$T/pack-builder" "$T/.github" "$T/loader" -type f -print0)
[ -z "$crlf" ] || die "files with CR line endings (would break on the Linux runners):$crlf"

files="$(find "$T/pack-builder" "$T/.github" "$T/loader" -type f | wc -l)"
cat <<EOF
done: $files files in $T

Next steps:
  cd "$T"
  git add -A
  git commit -m "pack builder $(date -u +%F)"
  git push
Then on github.com: Actions -> "Build packs" -> Run workflow (or: git tag packs-v1 && git push origin packs-v1).
Details (Russian): pack-builder/github/README.md
EOF
